import { createElement, type ComponentType } from 'react';
import * as Lucide from 'lucide-react';
import type { LucideIcon, LucideProps } from 'lucide-react';

export type IconProps = LucideProps & { weight?: 'Filled' | 'Outline' };
export type IconComponent = ComponentType<IconProps>;

// Keep a single, restrained outline family across the desktop interface.
function icon(Component: LucideIcon): IconComponent {
  return ({ weight: _weight, strokeWidth = 1.75, ...props }) => createElement(Component, { strokeWidth, ...props });
}

